#!/usr/bin/env python3
"""Writes the --char-* tokens from data/colors.json into src/theme/tokens.css, between its markers.

Run it after changing data/colors.json (src/colors/palette.test.ts checks they match).
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "src/theme/tokens.css"
START = "/* char tokens: generated by scripts/generate_char_tokens.py from data/colors.json. */"
END = "/* end char tokens */"


def block(colors, theme, selector, indent=""):
    lines = [f"{indent}{selector} {{"]
    for c in colors:
        lines.append(f"{indent}  --char-{c['id']}: {c[theme]['fill']};")
        lines.append(f"{indent}  --char-{c['id']}-ink: {c[theme]['ink']};")
    lines.append(f"{indent}}}")
    return "\n".join(lines)


def main():
    colors = json.loads((ROOT / "data/colors.json").read_text())["colors"]
    generated = "\n".join(
        [
            START,
            block(colors, "light", ":root,\n.char-theme-light"),
            "",
            "@media screen {",
            block(colors, "dark", ":root[data-theme='dark']", "  "),
            "}",
            "",
            "@media screen and (prefers-color-scheme: dark) {",
            block(colors, "dark", ":root:not([data-theme])", "  "),
            "}",
            "",
            block(colors, "dark", ".char-theme-dark"),
            END,
        ]
    )
    text = TOKENS.read_text()
    pattern = re.compile(re.escape(START) + r".*?" + re.escape(END), re.S)
    text = pattern.sub(generated, text) if pattern.search(text) else text.rstrip() + "\n\n" + generated + "\n"
    TOKENS.write_text(text)


if __name__ == "__main__":
    main()
